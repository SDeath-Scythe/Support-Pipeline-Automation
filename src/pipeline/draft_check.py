def _numbers(text: str) -> set[str]:
    return {re.sub(r"[,٬.]", "", n) for n in _NUMBER.findall(clean(text))}


def _normalise(text: str) -> tuple[str, list[int]]:
    """The draft as the rules read it, keeping where each character came from (see clean.fold)."""
    return fold(text)


def _raw(pos: list[int], start: int, end: int) -> tuple[int, int]:
    """A span in the normalised text, as a span in the draft as written."""
    return pos[start], pos[end - 1] + 1


def _whole_words(text: str, start: int, end: int) -> tuple[int, int]:
    """Widen a span to whole words ("فلوس" inside "الفلوس", "خلال يوم" of "خلال يومين"), for highlighting."""
    while start > 0 and not text[start - 1].isspace():
        start -= 1
    while end < len(text) and not (text[end].isspace() or text[end] in ".،,!?؟؛;:"):
        end += 1
    return start, end


def _squash(s: str) -> str:
    return " ".join(s.translate(_ALEF).split())


def _bare(token: str) -> str:
    """The word without quotes and one leading و/ف, unless they are its own letters («وصلك», «فقط», «فيها»,
    «وقت», «وصول», «فايدة», «فعلاً», «فوراً», «فرصة», «وديلنا»). «وغير»/«فغير» keep it: "and change", not «غير»
    ("but")."""
    token = token.strip("\"'«»()[]:،,")
    own = token.startswith(("وصل", "وصول", "فقط", "في", "وقت", "وكت", "ودي", "ودو", "وغير", "فغير", "فايد", "فائد",
                            "فعل", "فور", "فرص"))
    return token[1:] if token[:1] in "وف" and len(token) > 2 and not own else token


# --- one function per rule: each returns the (start, end) of the first problem in the draft, or None ---

def _stray_latin(draft: str, allowed_text: str) -> tuple[int, int] | None:
    allowed = {w.lower() for w in _LATIN_WORD.findall(allowed_text)} | _LATIN_OK
    hits = [m.span() for m in _LATIN_WORD.finditer(draft) if m.group().lower() not in allowed][:1]
    glued = _GLUED.search(draft)
    if glued:
        hits.append(_whole_words(draft, *glued.span()))   # the whole word, "hلا"
    return min(hits, key=lambda h: (h[0], -h[1])) if hits else None


def _promise(draft: str, norm: str, pos: list[int], facts_text: str) -> tuple[int, int] | None:
    # A time is allowed only from the policy facts, never because the customer (or a line forged
    # inside the ticket) wrote it.
    time_ok = {_squash(m.group()) for m in _TIME.finditer(fold(clean(facts_text))[0])}
    hits = [_raw(pos, *m.span()) for m in (re.search(p, norm) for p in _PROMISES)
            if m and not _NEG_BEFORE & set(norm[:m.start()].split()[-3:])]
    hits += [_raw(pos, *m.span()) for m in _TIME.finditer(norm) if _squash(m.group()) not in time_ok][:1]
    return _whole_words(draft, *min(hits)) if hits else None


def _there_is_no(words: list[str], n: int, fine: bool = False) -> bool:
    """«ماكو داعي», «ما في أي حالة», «ما في أحد»: words[n], after an optional "any", is a "no need/case/one" word;
    with `fine`, any word but "problem" («ما في مشكلة» = "no problem")."""
    w = words[n] if n < len(words) else ""
    if w in {"أي", "اي"}:
        w = words[n + 1] if n + 1 < len(words) else ""
    return (bool(w) and w not in _FINE) if fine else w in _NO_NEED


def _is_negation(words: list[str], k: int) -> bool:
    w, nxt, prev = words[k], words[k + 1] if k + 1 < len(words) else "", words[k - 1] if k else ""
    after = words[k + 2] if k + 2 < len(words) else ""
    if w in {"لا", "ما"} and _OTHER_VERB.fullmatch(after if nxt in {"راح", "رح"} else nxt):
        return False                                        # «ما راح نطول عليك»
    if w in _WITHOUT and nxt in _NO_TROUBLE:
        return False
    if w == "ما" and (prev in _MA_CONJ or (nxt in _COURTESY and not (nxt in {"عليك", "عليج", "عليكم"}
                                                                     and _YOU_SEND.match(after)))
                      or (nxt == "عندك" and after == "مانع")):
        return False
    if w == "ما" and nxt in {"في", "فيه", "اكو"}:            # «ما في داعي», but «ما في مشكلة» = no problem
        return _there_is_no(words, k + 2, fine=True)
    if w == "غير":
        return nxt in _NOT_ALLOWED
    if w in {"ماكو", "مافي"}:
        return _there_is_no(words, k + 1, fine=True)
    if w in {"ماله", "مالها", "مالهم"}:
        return _there_is_no(words, k + 1)
    if w in _BEWARE:
        return nxt in {"من", "عن"}
    if w in _DANGER:
        return prev == "من" or k == 0
    if w in _NEGATIONS:
        return True
    return (bool(_GLUED_NEG.fullmatch(w)) and not w.startswith(("لان", "مانع"))   # «لانه» = because
            and not _OTHER_VERB.fullmatch(w[2:]))


def _after_preposition(pfx: str) -> bool:
    """«شنو المشكلة بالرمز»: a secret after ب/ل is talked about, not asked for."""
    p = pfx.lstrip("وف").rstrip("ـ")
    return p.startswith("ب") or p in ("ل", "لل")


def _to_us(words: list[str], i: int) -> bool:
    """«تدزلنا», «ترسل لنا»: the request at word i is to us."""
    return bool(re.search(r"(?:لنا|النا|لي|نا|ني)$", words[i])) or words[i + 1:i + 2] in [[u] for u in _US]


def _courtesy_run(words: list[str], j: int) -> int:
    """How many words right before word j are fillers or courtesy phrases: four in «دزلنا بأسرع وقت ممكن رجاءً
    الرمز», two in «نحتاج منك لو سمحت الرمز» (see _FILLER, _COURTESY_PHRASE)."""
    n = j
    while n:
        size = next((k for k in (4, 3, 2, 1) if k <= n and (_COURTESY_PHRASE.fullmatch(" ".join(words[n - k:n]))
                                                            or (k == 1 and words[n - 1] in _FILLER))), 0)
        if not size:
            break
        n -= size
    return j - n


def _item(w: str) -> bool:
    """A word that can be part of a list of things asked for (see _ITEM_NOUNS)."""
    return bool(re.match(r"(?:ب|ل|لل)?ال", w)) or w in _ITEM_NOUNS or w in _FILLER or w in _US or w.isdigit()


def _where(after: str) -> str:
    """Where the clause after the secret says it goes: "app" («اكتب الرمز بالتطبيق»), "here" («... هنا بالرد مو
    بالتطبيق», «اللي ظهرلك بالتطبيق هنا بالمحادثة»: where it appeared) or "". A place after «مو» doesn't count."""
    def first(rx: re.Pattern) -> re.Match | None:
        return next((m for m in rx.finditer(after) if _bare((after[:m.start()].split() or [""])[-1]) not in _NOT_THERE),
                    None)
    app, here = first(_IN_APP), first(_HERE)
    if app and here and here.group() == "هنا" and after[here.end():app.start()].isspace():
        return "app"                                        # «اكتب الرمز هنا بالتطبيق»: here, in the app
    if app and here and _ARRIVED.fullmatch(_bare((after[:app.start()].split() or [""])[-1])):
        return "here"
    if app and not (here and here.start() < app.start()):
        return "app"
    return "here" if here else ""


def _denied_after(after: str) -> bool:
    """«دزلنا صورة الهوية والرمز لا تشاركه», «- الرمز ما نحتاجه»: a negation in the three words after the secret, or
    "keep it to yourself": «انطيه الهوية والرمز خليه عندك»."""
    tw = [_bare(x) for x in after.split()[:4]]
    return (any(_is_negation(tw, k) for k in range(min(3, len(tw))))
            or (tw[:1] in (["خليه"], ["خليها"]) and tw[1:2] in (["عندك"], ["عندج"], ["سري"], ["بينك"], ["لنفسك"])))


def _not_asked(words: list[str], j: int, after: str) -> bool:
    """Is the secret at word j named as something not to send (see _HIDE, _INSTEAD, _ABOUT_IT)?"""
    prev, prev2 = (words[j - 1] if j else ""), (words[j - 2] if j > 1 else "")
    if prev in _INSTEAD or _NOT_ITS_DIGITS.match(after) or _HIDE.fullmatch(prev):
        return True
    if prev in _EXCEPT and not any(_is_negation(words, k) for k in range(j - 1)):
        return True                                         # «أي تفاصيل غير الرمز»: "other than"
    if prev == "وقت" and prev2 in {"بأسرع", "باسرع", "أسرع", "اسرع"}:
        return False                                        # «بأسرع وقت»: soon
    if prev[:1] in "بل" and prev[1:] in _ABOUT_IT:
        return True                                         # «خبرنا بنوع الرمز», «بوقت وصول الرمز»
    return prev in _ABOUT_IT or (prev in _ITS_MESSAGE and prev2 in _ABOUT_IT)


def _request_at(words: list[str], i: int, j: int, pfx: str, after: str, app: bool = False, cant: str = "",
                question: bool = False, us: bool = False, listed: bool = False) -> bool:
    """Is word i a request for the secret that starts at word j? `after` is the clause after the secret, `app`
    whether the sentence names a step in the app («افتح التطبيق»), `cant` what _cant says of the sentence,
    `question` whether the clause ends in «؟», `us` whether "to us" follows the secret («ارسل الرمز إلنا»), `listed`
    whether the secret is a later item of a list after word i."""
    w, between, prev = words[i], words[i + 1:j], words[i - 1] if i else ""
    to_us = _to_us(words, i) or us
    if w.endswith("نا") and words[i + 1:i + 2] in (["لك"], ["الك"], ["إلك"], ["إليك"]):
        return False                                        # «ارسلنا لك رمز جديد»: we sent you
    b = between + ["", ""]
    if _PURPOSE & set(between) or any((x in _WHETHER and y not in _IF_PLEASE
                                       and not (y == "ما" and (z in _COURTESY or x in _WHENEVER))
                                       and not (x == "لو" and not y and not _ARRIVAL.match(after)))
                                      or (x == "كم" and y in {"مرة", "مره"})
                                      for x, y, z in zip(between, b[1:], b[2:])):
        return False                                        # «خبرنا إذا وصلك الرمز», «خبرنا حتى ندزلك رمز جديد»
    topic = any(x in {"شنو", "شني", "شنهو", "ايش", "إيش"} or (x[:1] == "ب" and x not in _FILLER) for x in between)
    if (w in _TELL or _INFORM.fullmatch(w)) and (any(_ARRIVED.fullmatch(x) for x in between)
                                                or (topic and _after_preposition(pfx))):
        return False                                        # «خبرنا أول ما يوصلك الرمز», «تخبرنا شنو المشكلة بالرمز»
    if any(_HIDE.fullmatch(x) or _CHANGE.fullmatch(x) for x in between):
        return False                                        # «دزلنا صورة الإشعار وخفي الرمز», «خبرنا لمن تغير الرمز»
    where = _where(after)
    if _TYPE.fullmatch(w) and (where == "app" or (app and where != "here")):
        return False
    if between[-1:] in (["طلب"], ["لطلب"], ["بطلب"]) or _TO_YOUR.match(after):
        return False                                        # «ارسل طلب رمز جديد», «ارسلنا رمز جديد على رقمك»
    by = next((x for x in range(i - 1, max(-1, i - 4), -1) if words[x] in _SYSTEM), None)
    system = ((by is not None and all(x in _ITSELF or (x == "من" and _NOUN.match(w)) for x in words[by + 1:i]))
              or words[i + 1:i + 2] in [[x] for x in _SYSTEM])   # «إذا لم يتمكن النظام من إرسال الرمز»
    if (system and _SEND.match(w) and not to_us and where != "here") or (prev in _WHO and _is_order(w)):
        return False                                        # «المنصة ترسل رمز التحقق», «منو دز الرمز»
    soon = [_bare(x) for x in after.split()[:2]]
    said = any(x in {"ما", "لا", "مو"} and _is_negation(soon, k) for k, x in enumerate(soon)) and "دام" not in soon
    if w in {"قلنا", "گلنا", "كلنا"} and (_BEFORE_NOW & set(between) or said):
        return False                                        # «گلنا بالرد السابق الرمز لا تشاركه»: we said, but
                                                            # «گلنا الرمز أول ما يوصلك» asks
    if _NOUN.match(w):
        again = prev in {"إعادة", "اعادة"} and not set(words[max(0, i - 3):i]) & _ASKING   # «يرجى إعادة إرسال» asks
        if (prev in _PASSIVE | _ISSUE and not (us and prev in {"يتم", "تتم"})) or (
                not us and (again or prev in _RESEND - {"إعادة", "اعادة"})):
            return False                                    # «تم إرسال الرمز», «اضغط على إعادة إرسال الرمز»
        if all(x in _LEAD for x in words[:i]) and _RISK.search(" ".join(words)) and not us:
            return False                                    # «مشاركة الرمز ... تعرض حسابك للخطر»: the subject
        if all(x in _LEAD for x in words[:i]) and _NOT_NEEDED.match(after):
            return False                                    # «إرسال الرمز إلنا مو ضروري»
    if (_SEND.match(w) and not _WE_DID.search(w)) or (w in _TELL and not (w == "كلي" and prev in {"بشكل", "شكل"})):
        if w in {"گول", "قول"} and prev in _AS | {"بحسب", "على"}:
            return False                                    # «حسب قول الموظف الرمز يوصل»: a noun, "as he said"
        him = (_TO_HIM.search(w) or w in {"گول", "قول"}) and not to_us
        return not ((him and not _is_order(w))              # «حتى تنطيهم الرمز»: to them, but «انطيه الرمز» (our
                    or (him and _denied_after(after))       # agent) asks; «گله الرمز سري وما أنطيه» is advice;
                    or between[:1] in [[x] for x in _A_MOMENT])   # «عطني فرصة أتأكد من الرمز»
    if (_ALOUD.fullmatch(w) and between and between[0][:2] == "عل") or (w in _PUT and where == "here"):
        return True                                         # «اقرا عليه الرمز», «حط الرمز بالخاص»
    if us and _IS_SENT.fullmatch(w) and w[:1] == "ي":
        return True                                         # «يُرسل رمز التحقق إلينا بالرد»
    if question and w[:2] == "ما" and _SEND.match(w[2:]) and w[2:3] == "ت" and _to_us([w[2:]], 0) and all(
            x in _ADDRESS for x in words[:i]):
        return True                                         # «ماتدزلنا الرمز؟»: please
    m = _PAST_YOU.fullmatch(w)
    if m:                                                   # «إلا إذا دزيتلنا», «إذا ما دزيتلنا», «ليش ما دزيتلنا»
        before = words[max(0, i - 2):i]
        why = len(before) == 2 and before[0] in {"ليش", "ليه", "لويش"} and before[1] == "ما"
        return len(before) == 2 and ((before[0] in {"إلا", "الا", "بس"} and before[1] in _IF_NOT)
                                     or (before[0] in _IF_NOT and before[1] == "ما") or why) and (
            bool(m.group("us")) or to_us
            or ((cant in ("we", "it") or why) and where != "app" and (w != "كتبت" or where == "here")))
    if w in _WITH or (w == "علينا" and i and words[i - 1] in _REPLY):
        return not between and pfx.lstrip("وف").startswith("ب")
    if w in _REPLY and all(x in _REPLY_TO for x in between):
        return pfx.lstrip("وف").startswith("ب")             # «رد على هاي الرسالة برمز التحقق»
    without = w in _WITHOUT or (w == "غير" and prev == "من")  # «ما نگدر نكمل من غير الرمز»
    if without or w in _EXCEPT:                             # «ما نگدر نساعدك بدون الرمز», «... إلا بالرمز»
        return not between and cant == "we" and (without or pfx.lstrip("وف").startswith("ب"))
    before = words[max(0, i - 2):i]
    if w in _CHECK:                                         # «نحتاج نتأكد بالرمز اللي وصلك»
        return prev.startswith(_NEED) and not between and pfx.lstrip("وف").startswith("ب")
    if _SOFT.match(w) or w in _KNOW:
        if _ENTER.match(w) and not _HERE.search(after):
            return False                                    # «يرجى إدخال رمز التحقق»: into the app
        return (any(x in _ASKING for x in before) or before == ["يا", "ريت"]
                or (w in _KNOW and (prev.startswith(_NEED) or (question and prev in _WE_CAN)) and not between)
                or (len(before) == 2 and before[0] in _WITHOUT and before[1] == "ما" and cant == "we"))
    if (w.startswith(_NEED) or (w in _WAIT and _FROM_YOU & set(words))
            or (w in {"اطلب", "أطلب"} and between[:1] in [[f] for f in _FROM_YOU])):   # «اسمحلي اطلب منك الرمز»
        if _ASK_VERB.fullmatch(w) and where == "app":
            return False                                    # «احنا نطلب الرمز بس داخل التطبيق»
        return ((listed or (len(between) <= 5 and (all(x in _FILLER or x in _EXCEPT for x in between)
                                                   or _courtesy_run(between, len(between)) == len(between))))
                and not _ARRIVES.match(after))
    if w in _WHAT or (w == "ما" and question and between[:1] in (["هو"], ["هي"])   # MSA «ما هو الرمز الذي وصلك؟»
                      and re.search(r"(?:ك|ج|كم)(?!\w)", after)):
        return (all(x in {"هو", "هي", "كان", "چان", "جان"} for x in between) and not _after_preposition(pfx)
                and not _ON_SCREEN.match(after))
    return False


def _reporters(words: list[str], lo: int, hi: int) -> set[str]:
    """The quoting words in words[lo:hi]: not the noun «طلب» («نكمل طلب التحويل»), «كلك ذوق», or "as he told you"
    («مثل ما قال زميلي», «مثل ما طلب منك الموظف»): a colleague of ours, cited."""
    out = set()
    for x in range(max(0, lo), hi):
        w, nxt = words[x], words[x + 1] if x + 1 < len(words) else ""
        as_said = words[max(0, x - 2):x] in [[a, "ما"] for a in _AS] or words[x - 1:x] in (["مثلما"], ["كما"])
        by_them = bool((_FRAUD | {"أحد", "احد", "شخص", "واحد"}) & set(words[x + 1:x + 3]))   # «مثل ما گلك المحتال»
        if not ((w == "طلب" and nxt not in _FROM_YOU) or (w == "كلك" and nxt in _KIND)
                or (w in _REPORTED_PAST and as_said and not by_them)):
            out.add(w)
    return out


def _anyone(words: list[str]) -> set[str]:
    """The "if", "anyone" and fraudster words in `words` (see _IF_OR_ANYONE), but not «إذا ممكن», «لو سمحت»
    ("please")."""
    return {w for x, w in enumerate(words) if w in _IF_OR_ANYONE
            and not (w in _IF_NOT and words[x + 1:x + 2] and words[x + 1] in _IF_PLEASE)}


def _someone_else_asks(words: list[str], i: int, earlier: frozenset[str] = frozenset()) -> bool:
    """The request at word i is quoted, not made: «إذا أحد طلب منك تدز الرمز», «ما نطلب منك ... تدزلنا الرمز»,
    «محد من الموظفين راح يطلب منك تدزله الرمز». The quoting verb must be within four words of the request, with
    no "only" or "so" between: «ما نطلب منك هواية بس دزلنا الرمز» and «لا يمكننا الإكمال لذا نطلب منك ...» ask. After
    "if anyone" or a fraudster it may be eight words back («المحتال يگلك كل شي راح يتصلح بس دزلي الرمز»), and a
    message «الرسالة تگول انطينا الرمز» or an earlier "it's fake" (`earlier`, the sentence before this clause) counts."""
    before, near = words[max(0, i - 12):i], _reporters(words, i - 4, i)
    anyone = _anyone(before) | (earlier & _FRAUD)
    now = near & _REPORTED_NOW
    if (near & _REPORTED_PAST or (now and (anyone or _MESSAGE & set(before)))
            or (anyone and _reporters(words, i - 8, i) & (_REPORTED_PAST | _REPORTED_NOW))):
        return True
    return any(_ASK_VERB.fullmatch(words[k]) and not (_EXCEPT | {"بس", "فقط"}) & set(words[k + 1:i])
               and any(_is_negation(words, q) and not _BREAK & set(words[q + 1:k]) for q in range(max(0, k - 4), k))
               for k in range(max(0, i - 12), i))


def _is_order(w: str) -> bool:
    """An order («دزلنا», «ارسل», «قلي»), not a "you" form («تدزلنا») or a noun («إرسال»)."""
    return not w.startswith("ت") and (w in _TELL or (bool(_SEND.match(w)) and not _NOUN.match(w)))


def _passes(words: list[str], x: int) -> bool:
    """Does word x pass a negation on to the word after it (see _PASS)?"""
    w = words[x]
    return (w in _PASS or bool(_TAKES.fullmatch(w) or _SAY.fullmatch(w))
            or words[x + 1:x + 2] in (["او"], ["أو"]))           # «ما تحتاج تكتب أو ترسل الرمز»


def _same_person(can: str, w: str) -> bool:
    """After "can" («نگدر») comes a verb of the same person («ما نگدر نطلب منك»), not a "you" form or "must"."""
    modal = (w.startswith(_NEED) and not _ASK_VERB.fullmatch(w)) or w.startswith("محتاج") or w in _MODAL
    return w[:1] == can and not modal


# A verb that happens by itself takes no request after it: «الحوالة ما راح تتعطل تدزلنا الرمز», «فلوسك ما راح تضيع
# ترسلنا الرمز» ask (a comma dropped).
_BY_ITSELF = re.compile(r"[يت]ت\w{3,}|[يت]ضيع")


def _reaches(words: list[str], k: int, i: int, free: bool = False, noun: bool = False) -> bool:
    """Does the negation at word k reach word i (see _PASS and _reaching_negation)? "No harm" («ما يضر», «مو
    مشكلة»), "only", "so", a verb like "worry" or "be late" («ما يصير تتأخر ترسلنا») and a plain ask word end it.
    "Can" passes it only to a verb of the same person («ما نگدر نطلب منك», not «ما نگدر هسه تدزلنا الرمز»), and
    "think/know" only when it is the negated verb and "that", a pronoun or a "need" word follows («ما أظن إنه
    لازم ترسل», not «ما نعرف هسه تدزلنا الرمز»). «مو» also has the free slot («مو آمن ترسل الرمز»), and a noun two,
    after any verb: «ما نگدر نعيد إرسال الرمز», «ما نتحمل مسؤولية مشاركة الرمز»."""
    slots, used = (2 if noun else 1) if free and words[k] in {"ما", "لا", "مو"} else 0, False
    can = think = ""
    for x in range(k + 1, i):
        w = words[x]
        if ((w == "حتى" and _EVEN_AFTER.fullmatch(words[x - 1]))   # «مو لازم حتى ترسل الرمز»: "even"
                or (x == k + 2 and words[k] == "محد" and words[k + 1] == "من")):   # «محد من الموظفين»
            continue
        if (w in _BREAK or w in _FINE or _OTHER_VERB.fullmatch(w) or (w in _ASK_ONLY and x > k + 1)
                or (w in {"شي", "شيء"} and words[x - 1] in {"يصير", "صار"})):
            return False
        nxt = words[x + 1] if x + 1 < i else ""
        if ((w in _HOLDS | {"بي", "له", "لها", "منه", "منها"} and nxt in _NO_NEED)
                or (w in {"شي", "شيء"} and _TAKES.fullmatch(nxt))):
            continue                                        # «ما بيه داعي ترسل», «ما له داعي», «مو شي ضروري»
        if can and w not in _PASS:
            if not _same_person(can, w):
                return False
            can = ""
        if think and (w in _THAT or _TAKES.fullmatch(w)):
            think = ""
        takes = bool(_TAKES.fullmatch(w))
        if used and takes:
            return False                                    # «ما نگدر نكمل لازم تدزلنا الرمز»: a new request
        if w in _THINK and (x == k + 1 or words[x - 1] in _AUX):
            think = w
            continue
        if _passes(words, x) and w not in _THINK:
            can = w[:1] if _CAN.fullmatch(w) else can
            slots = slots if noun or not takes else 0
            continue
        if not slots or (not noun and (w.startswith("ن") and not w.endswith(("ك", "ج", "كم"))
                                       or (_BY_ITSELF.fullmatch(w) and words[k] != "لا"))):
            return False
        slots, used = slots - 1, True
    w = words[i]
    if noun:
        return True
    return (not can or _same_person(can, w)) and not (think and not (w.startswith(_NEED) or _TAKES.fullmatch(w)
                                                                     or w in _WHAT))


def _or_reaches(words: list[str], k: int, i: int) -> bool:
    """«ما تحتاج تروح للفرع أو ترسل الرمز»: the request after «أو» shares the negation of a "you" verb before it,
    but in «ما نگدر نكمل تعال للفرع أو ترسلنا الرمز» the negation is spent on «نكمل»."""
    alt = next((x for x in range(k + 1, i - 1) if not (words[x] in _PASS or _TAKES.fullmatch(words[x]))), None)
    return (alt is not None and words[alt].startswith("ت") and i - 1 - alt <= 3
            and not any(_is_order(w) or w.startswith(("ت", "ن")) for w in words[alt + 1:i - 1]))


def _reaching_negation(words: list[str], i: int, free: bool = False, noun: bool = False) -> int | None:
    """The negation that reaches word i (see _PASS): the nearest one in the six words before it, if every word
    between passes it on, or the «ولا» of «لا X ولا Y» with up to three words after it («لا احنا ولا البنك نحتاج»).
    With `free` (a "you" form or a noun), «ما»/«لا»/«مو» may also pass one verb of its own, before any word that
    takes the request: «ما يجوز تشارك الرمز», «ما ننصحك ترسل الرمز». A "we" verb only with "you" on it, so «ما نطول
    تدزلنا الرمز» asks."""
    for k in range(i - 1, max(-1, i - 7), -1):
        if not _is_negation(words, k):
            continue
        if words[k] == "لا" and "لا" in words[max(0, k - 4):k] and i - k <= 4:
            if any(x.startswith("ت") for x in words[k + 1:i]):
                return None                                 # «لا تروح ولا تتصل ترسلنا الرمز»: a third verb
            return k
        if words[i - 1] in {"او", "أو"} and _or_reaches(words, k, i):
            return k
        return k if _reaches(words, k, i, free, noun) else None
    return None


def _coordinated(words: list[str], i: int, joined: bool) -> bool:
    """«لا تصدق المتصل وتنطيه الرمز», «ما في داعي تزعج نفسك وترسل الرمز», «ما راح نتصل بيك ونطلب الرمز»: a verb
    joined by «و» to a negated verb of the same person shares its negation. Not «لا تتأخر وترسلنا الرمز» (see
    _OTHER_VERB), «ما نگدر نكمل وتدزلنا الرمز», or a need: «ما نگدر نكمل ونحتاج منك الرمز» says two things."""
    need = (words[i].startswith(_NEED) or words[i] in _WAIT) and not _ASK_VERB.fullmatch(words[i])
    if not joined or words[i][:1] not in "تن" or need:
        return False
    for k in range(i - 1, max(-1, i - 8), -1):
        if words[k] in _BREAK:
            return False
        if not _is_negation(words, k) or _condition(words, k):
            continue
        verb = next((w for w in words[k + 1:i] if w not in _PASS), "")
        return verb[:1] == words[i][:1] or (words[i][:1] == "ت" and verb[:1] != "ن" and bool(_TAKES.fullmatch(verb)))
    return False


def _condition(words: list[str], k: int) -> str:
    """"without" for «بدون (ما)», «من غير ما», "if" for «إذا ما», «لو ما», «ما لم», «إن لم», «في حال عدم», "" for
    a plain negation."""
    w, prev = words[k], words[k - 1] if k else ""
    if w in _WITHOUT or (w == "ما" and (prev in _WITHOUT or (prev == "غير" and words[k - 2:k - 1] == ["من"]))):
        return "without"
    if ((w in {"ما", "لم"} and prev in _IF_NOT) or (w == "لم" and prev == "ما")
            or (w in {"عدم", "بعدم"} and prev in {"حال", "حالة", "حاله"})):
        return "if"
    return ""


def _cant(words: list[str]) -> str:
    """"we" if the sentence says we can't go on («ما نگدر نكمل», «ما راح يكمل الطلب», «لا يمكننا», «صعب نكمل») or
    threatens («الطلب ينلغي»), "it" for «الحساب ما راح يتفعل» (see _YOURS), "you" for «ما تگدر تكمل» or «لا تسوي
    شي», "free" for «تگدر تكمل» or «عادي» with no negation, else ""."""
    found = ""
    for k, w in enumerate(words):
        hard = w == "صعب" and not (k and _is_negation(words, k - 1))
        if (not (hard or _is_negation(words, k)) or w == "محد" or _condition(words, k)
                or (k and words[k - 1] in _IF_NOT)):
            continue
        n = k + 1
        while n < len(words) and words[n] in {"راح", "رح", "عاد", "يصير", "للأسف", "للاسف"}:
            n += 1
        verb = w[2:] if _GLUED_NEG.fullmatch(w) else words[n] if n < len(words) else ""
        subject = {words[n + 1] if n + 1 < len(words) else "", words[k - 1] if k else ""}   # «طلبك ما راح يتم»
        if _GO_ON.fullmatch(verb) or (_GO_ON_IT.fullmatch(verb) and verb[:1] == "ي" and subject & _PROCESS):
            return "we"
        if _GO_ON_IT.fullmatch(verb) and subject & _YOURS:
            found = "it"
        elif _GO_ON_YOU.fullmatch(verb) and not found:
            found = "you"
    if not found and any(_THREAT.fullmatch(w) and not any(_is_negation(words, q) for q in range(max(0, k - 2), k))
                         for k, w in enumerate(words)):
        return "we"
    if not found and any(_YOU_CAN.fullmatch(w) and not (k and _is_negation(words, k - 1)) for k, w in enumerate(words)):
        return "free"
    return found


def _we_did(words: list[str], lo: int, i: int) -> bool:
    """The "we" past form at word i follows «احنا» in words[lo:i], with only "never/yet" words between, and is a send
    verb or negated: «احنا ارسلنا الرمز», «احنا ولا مرة انطيناه» (see _PAST_WE)."""
    return any(words[x] in {"احنا", "نحن"} and all(y in _PAST_OK for y in words[x + 1:i])
               and (bool(_WE_SENT.fullmatch(words[i])) or bool({"لا", "ما"} & set(words[x + 1:i])))
               for x in range(lo, i))


def _negated(words: list[str], i: int, j: int, cant: str = "", question: bool = False, joined: bool = False,
             us: bool = False) -> bool:
    """Does the request at word i, for the secret at word j, not ask after all? Negated by a word between them
    or by a negation that reaches it, quoted, or "we sent/said". `joined`: the request has a «و» on it; `us`:
    "to us" follows the secret."""
    w, between = words[i], words[i + 1:j]
    if any(_is_negation(words, k) for k in range(i + 1, j)):
        return True
    if _EXCEPT & set(between) or w in _WITHOUT | _EXCEPT or ("بس" in between and between[0] != "بس"):
        return False                                        # «ما نحتاج منك غير الرمز»: nothing but the secret
    say = next((s for s in range(max(0, i - 3), i) if _SAY.fullmatch(words[s]) or (s == i - 1 and words[s] in _HOLDS)),
               None)
    if say is not None and not any(_is_negation(words, k) for k in range(say + 1, i)):   # «نگلك لا تشارك الرمز»
        lo = max(0, say - 1) if words[say][:1] in "اأ" else max(0, say - 5)   # «اگلك» (I tell you): our own voice
        return any(_is_negation(words, k) or words[k] in {"ماكو", "مافي"} for k in range(lo, say))
    if _PAST_WE.fullmatch(w) and (_we_did(words, max(0, i - 4), i) or (i and words[i - 1] in _AS)
                                  or words[max(0, i - 2):i] in [[a, "ما"] for a in _AS]):
        return True                                         # «احنا ما بعد ارسلنا الرمز», not «احنا هنا ... انطينا»
    if _ASK_VERB.fullmatch(w):                              # «ما نگدر نطلب منك الرمز», «ما يجي موظف يطلب منك الرمز»
        return (_reaching_negation(words, i) is not None or _coordinated(words, i, joined)
                or any((_is_negation(words, k) or words[k] in _FORBID)
                       and ((w[:1] == "ي" and _reaches(words, k, i, free=True, noun=True))
                            or all(x in _PASS | _RIGHT | _MAY or _TAKES.fullmatch(x) for x in words[k + 1:i]))
                       for k in range(max(0, i - 4), i))
                or any(_is_negation(words, k) and any(_CONTACT.fullmatch(x) for x in words[k + 1:i])
                       and all(x in _PASS | _YOU_OBJ | _MESSAGE | _HOLDS or _CONTACT.fullmatch(x)
                               for x in words[k + 1:i])     # «ما راح نتصل بيك نطلب كلمة السر»
                       for k in range(max(0, i - 6), i)))
    noun = bool(_NOUN.match(w))
    k = _reaching_negation(words, i, free=w.startswith("ت") or noun, noun=noun)
    if k is None:
        return _coordinated(words, i, joined)
    if words[k] == "بالك" and words[k - 1:k] in (["خلي"], ["خلّي"]) and (_is_order(w) or _to_us(words, i) or us):
        return False                                        # «خلي بالك دزلنا الرمز», «... تدزلنا الرمز»: make sure
    if _is_order(w):                                        # Iraqi says «لا تدز», never «ما دز»: «ما دز» is the past
        return words[k] in _NOUN_NEG or (words[k] in {"ما", "لا", "لم", "محد"} and not (words[k] == "لا" and k == i - 1)
                                         and all(x in _PAST_OK for x in words[k + 1:i]))
    to_us = _to_us(words, i) or us
    kind = _condition(words, k) if all(x in {"راح", "رح", "أن", "ان"} for x in words[k + 1:i]) else ""
    if kind:                                                # «إذا ما تريد ترسل الرمز» is not a condition on it
        return not (cant in ("we", "it") or (to_us and cant != "free"))
    opener = all(x in _ADDRESS for x in words[:k])          # «عيوني ما تدزلنا الرمز؟»
    why = words[k - 1:k] in (["ليش"], ["ليه"], ["لويش"])
    if (to_us or why) and words[k] == "ما" and k == i - 1 and (w.startswith("ت") or _PAST_YOU.fullmatch(w)) and (
            (question and opener) or why):
        return False                                        # «ليش ما ترسل الرمز؟», «ما تدزلنا الرمز؟»: please
    can_ask = ((words[k] in {"ما", "مو"} and words[k + 1:i] in [[c] for c in _CAN_ASK])
               or (words[k][:2] == "ما" and words[k][2:] in _CAN_ASK and k == i - 1))
    if to_us and question and opener and w.startswith("ت") and can_ask:
        return False                                        # «ما تگدر تدزلنا الرمز؟», «ماتگدر تدزلنا الرمز؟»
    return True


def _secrets(text: str) -> list[tuple[int, int, str]]:
    found = [(m.start(), m.end(), m.group("pfx") or "") for m in CREDENTIAL.finditer(text)
             if not _ON_RECEIPT.match(text, m.end())]
    for m in _SECRET_EXTRA.finditer(text):
        before = [_bare(w) for w in text[max(0, m.start() - 80):m.start()].split()[-4:]]
        if m.group("msg") and before[-1:] and (before[-1] in _SHOT or before[-1].startswith(("صور", "لقط"))):
            continue                                        # «صورة الرسالة اللي وصلتك»: see _HOLDS for one with the code
        if not _LAST & set(before):
            found.append((m.start(), m.end(), m.group("pfx") or ""))
    return sorted(found)


def _sentence(norm: str, stops: list[int], i: int) -> tuple[int, int]:
    """The span of the sentence around norm[i] («ما نگدر نكمل، بدون ما تدزلنا الرمز»); `stops` is where each
    .!?؟;\n is."""
    k = bisect_right(stops, i)
    return (stops[k - 1] + 1 if k else 0), (stops[k] if k < len(stops) else len(norm))


# «... فاكتبه بالتطبيق»: the sentence says to type the code into the app, so "we can't go on without it" is about
# the app, not a request to us.
_TYPED_IN_APP = re.compile(r"(?<!\w)[وف]?(?:ا|ت)?(?:كتب|دخل)\w*(?:\s+\S+){0,3}?\s+(?:بال|ب|في\s+(?:ال)?|داخل\s+(?:ال)?)"
                           r"(?:تطبيق|برنامج)")
_OPEN = {'"': '"', "«": "»", "“": "”"}


def _in_quote(norm: str, s0: int, at: int) -> bool:
    """Is norm[at] inside quotes opened after a say or write word earlier in the sentence: «رسالة تگول "حسابك راح
    ينقفل، ارسل الرمز"»? A comma inside the quotes splits the clause from its say word."""
    seg = norm[s0:at]
    o = max(seg.rfind(q) for q in _OPEN)
    close = _OPEN[seg[o]] if o >= 0 else ""
    if o < 0 or (close == '"' and seg.count('"') % 2 == 0) or (close != '"' and close in seg[o:]):
        return False
    cue = _bare((seg[:o].split() or [""])[-1])
    return cue in _HOLDS | _WRITTEN | _REPORTED_NOW or bool(_SAY.fullmatch(cue))


def _answered(norm: str, at: int) -> bool:
    """The sentence at norm[at] answers a "what is the code?" («هو رقم مؤقت لتأكيد العملية») and asks nothing of its
    own: not «هو رقم من ست خانات، دزه إلنا»."""
    m = _ANSWER.match(norm, at)
    words = [_bare(x) for x in _STOP.split(norm[m.end():] if m else "", maxsplit=1)[0].split()]
    return bool(m) and not any(_SEND_TO.fullmatch(x) or x in _US or x.endswith(("لنا", "النا")) for x in words)


def _asks_secret(norm: str, pos: list[int]) -> tuple[int, int] | None:
    needs = False                                           # the clause before, in the same sentence, needs something
    stops = [m.start() for m in _STOP.finditer(norm)]
    seen: dict[int, tuple[str, bool]] = {}                  # each sentence's _cant and app step, worked out once
    for clause in _CLAUSE.finditer(norm):
        text, base = clause.group(), clause.start()
        needs = needs and norm[base - 1:base] in "،,"
        question = norm[clause.end():clause.end() + 1] in ("؟", "?")
        answered = question and _answered(norm, clause.end() + 1)
        s0, s1 = _sentence(norm, stops, base)
        if s0 not in seen:
            typed = bool(_TYPED_IN_APP.search(norm, s0, s1))
            seen[s0] = ("" if typed else _cant([_bare(w) for w in norm[s0:s1].split()]),
                        bool(_APP_STEP.search(norm, s0, s1)))
        cant, app = seen[s0]
        earlier = frozenset(_bare(w) for w in norm[s0:base].split())
        tokens = list(_WORD.finditer(text))
        starts, lead = [t.start() for t in tokens], len(text) - len(text.lstrip())
        words = [_bare(t.group()) for t in tokens]
        for start, end, pfx in _secrets(text):
            head, tail = text[max(lead, start - 200):start], text[end:end + 200]   # near the secret is enough
            h = [_bare(x) for x in head.split()][-4:]
            negated = any(_is_negation(h, k) for k in range(max(0, len(h) - 3), len(h)))   # «ما نعرف الرمز شنو»
            waiting = _STILL_WAITING[0].search(head)
            if ((not negated and question and _POLITE_TAIL.fullmatch(tail)
                 and (_POLITE_ASK.fullmatch(head) or (not head.strip() and _PLEASE.search(tail))))
                    or (not negated and _WHAT_TAIL.match(tail) and not _after_preposition(pfx)
                        and not _ON_SCREEN.match(tail) and not answered)
                    or (waiting and (waiting.group("cond") or _STILL_WAITING[1].match(tail)))):
                return _raw(pos, base + lead, base + end)
            j = bisect_right(starts, start) - 1
            if j and words[j - 1] in {"ال", "بال", "لل"} and tokens[j - 1].end() < start:
                j -= 1                                      # «نحتاج منك الـ OTP», folded to «ال OTP»
                pfx = words[j] + pfx
            if (j == 1 and needs and words[0] in _EXCEPT | {"بس", "فقط"}
                    and not any(_is_negation(words, k) for k in range(len(words)))):
                return _raw(pos, base + tokens[0].start(), base + end)   # «ما نحتاج شي ثاني، بس الرمز»
            if j >= 2 and words[j - 1] == "من" and words[j - 2] in {"أرقام", "ارقام", "رقمين"}:
                j -= 2                                      # «شنو أول ثلاث أرقام من الرمز»: part of the secret
                while j and (words[j - 1] in _FIRST_DIGITS or words[j - 1].isdigit()):
                    j -= 1
            if _not_asked(words, j, tail) or (pfx.startswith("و") and (_denied_after(tail) or _ARRIVES.match(tail))):
                continue                                    # «... والرمز لا تشاركه», «... والرمز يوصلك»: a new clause
            us = bool(tail.split()) and _bare(tail.split()[0]) in _US
            # The request: at most four words before, more for "nothing but", a screenshot of the message that holds
            # it («صورة للرسالة اللي بيها الرمز»), or a list («ارسل لنا رقم الهاتف والاسم الكامل ورمز التحقق»).
            listed = pfx.startswith("و")
            back = (10 if listed else 7 if j and words[j - 1] in _HOLDS and _SHOT & set(words[max(0, j - 6):j])
                    else 6 if j and words[j - 1] in _EXCEPT else 4)
            fill = _courtesy_run(words, j)
            fill += fill < j and words[j - 1 - fill] in _US     # «ارسل لنا بأسرع وقت ممكن الرقم السري»
            soon = any(words[x] in _WHENEVER and words[x + 1] == "ما" for x in range(max(0, j - 5), j - 1))
            back = max(back, fill + 1) + 2 * soon       # «دزلنا بأسرع وقت ممكن رجاءً الرمز», «ارسل لنا متى ما وصلك»
            for i in range(j - 1, max(-1, j - 1 - back), -1):
                if listed and j - i > 4 and not _item(words[i + 1]):
                    break                                   # past four words, only the items of a list
                if _request_at(words, i, j, pfx, tail, app, cant, question, us, listed):
                    raw = tokens[i].group().strip("'»()[]:،,")
                    cue = words[i - 1] if i else ""             # «مكتوب بيها "ارسل الرمز"»: quoted
                    quoted = ((raw[:1] in "\"“«" and (cue in _HOLDS | _WRITTEN or bool(_SAY.fullmatch(cue))))
                              or _in_quote(norm, s0, base + tokens[i].start()))
                    joined = raw[:1] == "و" and raw[1:] == words[i]
                    own = answered and words[i] in _WHAT | {"ما"}
                    if (not (quoted or own or _negated(words, i, j, cant, question, joined, us)
                             or _someone_else_asks(words, i, earlier))
                            or _BUT_US.search(tail)):
                        return _raw(pos, base + tokens[i].start(), base + end)
                    break
        needs = any(w.startswith(_NEED) for w in words)
    for start, end, _ in _secrets(norm):                    # «وصلك الرمز؟ شنو هو؟», «الرمز اللي وصلك، شنو هو؟»
        m = _WHAT_NEXT.match(norm, end)
        if m and not _answered(norm, m.end()):
            return _raw(pos, start, m.end())
    return None


def _reported(words: list[str]) -> bool:
    """Someone else's request, told in a warning: «إذا أحد گالك ...», «المحتالين يگولون ...»."""
    rep = _reporters(words, 0, len(words))
    return bool(rep & _REPORTED_PAST) or bool((rep & _REPORTED_NOW or any(_SAY.fullmatch(x) for x in words))
                                              and (_anyone(words) or set(words) & _MESSAGE))


def _asks_for_it(norm: str, pos: list[int]) -> tuple[int, int] | None:
    """The secret named first, then "send it" within eight words, across a comma: «الكود اللي اجاك دزه النا». A
    question or a new line may come between: «وين الرمز؟ دزه حتى نكمل». "Send us the last one" and "tell us what you
    chose" count too: «إذا وصلك أكثر من رمز، دزلنا آخر واحد», «اختار رقم سري جديد وگلنا شنو اخترت». A "send it"
    that is negated or quoted stops only its own clause: «الرمز لا تكتبه بأي موقع. دزه إلنا بس هنا» asks."""
    stops = [m.start() for m in _STOP.finditer(norm)]
    for start, end, _ in _secrets(norm):
        n = bisect_left(stops, end)
        cut = stops[n] if n < len(stops) else None
        tokens = list(_WORD.finditer(norm, end, min(cut if cut is not None else len(norm), end + 400)))[:8]
        parts, part = [], 0                                 # a negation counts only up to the last comma
        for t in tokens:
            parts.append(part)
            part += t.group()[-1] in "،,"
        main = len(tokens)                                  # after a stop, only "send it" counts: «وين الرمز؟ دزه»
        if cut is not None:                                 # «ما وصلك رمز؟ إذا وصلك ابعثلنا ياه»
            more = list(_WORD.finditer(norm, cut + 1, stops[n + 1] if n + 1 < len(stops) else len(norm)))[:4]
            tokens, parts = tokens + more, parts + [part + 1] * len(more)
        words = [_bare(t.group()) for t in tokens]
        s0, s1 = _sentence(norm, stops, start)
        lead = norm[max(s0, start - 200):start].split()
        said = [_bare(w) for w in lead][-6:]                # the words before the secret
        if lead and said[-1] == "لا" and lead[-1][-1] not in "،,":
            continue                                        # «لا الرمز ولا الرقم السري نحتاجه منك»
        blocked = None                                      # the clause of a negated "send it"
        for k, w in enumerate(words):
            if parts[k] == blocked:
                continue
            nxt_w = words[k + 1] if k + 1 < len(words) else ""
            last_one = nxt_w in _LAST and [t.group() for t in tokens[k + 2:k + 3]] in (["واحد"], ["وحدة"], ["وحده"])
            chose = (nxt_w in _WHAT and bool(words[k + 2:k + 3]) and bool(_CHOSE.fullmatch(words[k + 2]))
                     and parts[k] == 0 and words[k + 3:k + 4] not in (["من"], ["بين"]))   # not «... من الخيارات»
            bare = (_BARE_ORDER.fullmatch(w) and nxt_w in _US | {"هنا"} and k <= 2 and parts[k] == 0
                    and (k + 2 >= len(words) or parts[k + 2] != parts[k] or words[k + 2] in _AFTER_BARE))
            if not (_SEND_IT.fullmatch(w) or (_SEND_TO.fullmatch(w) and (nxt_w in _IT or last_one)) or bare
                    or ((_SEND_TO.fullmatch(w) or w in _TELL) and chose)
                    or (_IS_SENT.fullmatch(w) and (_TO_US.match(norm, tokens[k].end())
                                                   or ("كتب" in w and _HERE_NEXT.match(norm, tokens[k].end()))))
                    or (_REACH_US.fullmatch(w) and nxt_w in _FROM_YOU)):
                continue
            if k >= main and not (_SEND_IT.fullmatch(w) or nxt_w in {"ياه", "اياه", "إياه", "ياها"}):
                continue                                    # «... الرمز. تكدر ترسل لنا رقم المستلم» is another thing
            back = [x for x in (said + words[:k])[::-1] if x not in _ITSELF]
            prev = back[0] if back else ""
            if prev in _SYSTEM | _WHO or nxt_w in _SYSTEM:
                break                                       # «النظام ارسله», «ما ندري منو دزه», «... دزه النظام»
            if nxt_w in _TO_ANYONE or (tokens[k].group()[:1] == "و" and _coordinated(said + words[:k + 1], len(said) + k,
                                                                                    True)):
                break                                       # «ترسله لأحد», «لا تصور الرسالة اللي بيها الرمز وتدزها»
            negs = [x for x in range(max(0, k - 3), k) if parts[x] == parts[k] and _is_negation(words, x)]
            order = not w.startswith(("ت", "ن", "م", "ي")) and not _NOUN.match(w)
            past = _PAST_WE.fullmatch(w) and _we_did(words, parts.index(parts[k]), k)
            gap = range(negs[-1] + 1, k) if negs else range(0)
            if negs and _PAST_WE.fullmatch(w):              # «الرمز ما انطيناه لأحد», not «ما نگدر انطيناه»
                hit = all(words[x] in _PAST_OK for x in gap) and not (words[negs[-1]] == "لا" and not gap)
            elif negs:
                hit = all(_passes(words, x) for x in gap) if order else _reaches(words, negs[-1], k, free=True)
            else:
                hit = False
            if past or hit or (negs and any(_SAY.fullmatch(words[x]) for x in gap)):
                blocked = parts[k]
                continue
            if words[k - 1:k] in (["او"], ["أو"]) and any(_is_negation(said, x) for x in range(len(said))[-4:]):
                break                                       # «ما يحتاج تخبرنا بالرمز أو تكتبه»
            if _reported(said + words[:k]):
                break
            rest = _STOP.split(norm[tokens[k].end():tokens[k].end() + 200], maxsplit=1)[0]
            if "كتب" in w and (_IN_APP.search(rest) or not (_HERE.search(rest) or w.endswith(("لنا", "النا", "لي")))):
                break                                       # «الرمز صالح لخمس دقائق، فاكتبه بسرعة»: in the app
            return _raw(pos, start, tokens[k].end())
    return None


_CLAUSE_END = re.compile(r"[.،,!?؟؛;\n]")
_MARKER = re.compile(r"[ \t]*(?:[-•*·●▪]|\d{1,2}[ \t]*[.)-]|\(\d{1,2}\))[ \t]*")
_INLINE_SEP = re.compile(r"[،,]|(?<!\S)(?:\d{1,2}\)|\(\d{1,2}\))[ \t]*")   # «صورة الهوية 2) الرقم السري»


def _asks_in_list(norm: str, pos: list[int]) -> tuple[int, int] | None:
    """The secret as an item of a list after a request and a colon: «حتى نكمل نحتاج منك:\n- الرمز اللي وصلك\n- صورة
    الهوية», «المطلوب منك:\n١. صورة الهوية\n٢. رمز التحقق», «نحتاج منك: صورة الهوية، رمز التحقق», «نحتاج: 1) صورة
    الهوية 2) الرقم السري», «pls send:\n- full name\n- OTP». The items are the marked lines below the colon («-», «•»,
    «1.»), or the rest of the sentence split at commas and at «1)» or «(1)»."""
    for colon in re.finditer(":", norm):
        start = max(norm.rfind(c, 0, colon.start()) for c in ".!?؟\n") + 1
        head = [_bare(w) for w in norm[start:colon.start()].split()][-6:]
        latin = _LATIN_HEAD.search(norm, start, colon.start())
        if not ((latin and not _LATIN_NOT.search(norm, start, latin.start()))
                or any(all(_item(x) for x in head[i + 1:]) and _request_at(head, i, len(head), "", "", listed=True)
                       and not _negated(head, i, len(head)) for i in range(len(head)))):
            continue
        items = []
        if norm[colon.end():].split("\n", 1)[0].strip():   # on the same line, up to the end of the sentence
            stop = _STOP.search(norm, colon.end())
            seg = norm[colon.end():stop.start() if stop else len(norm)]
            seps = [m.span() for m in _INLINE_SEP.finditer(seg)]
            items = [(colon.end() + a, colon.end() + b) for a, b in zip([0] + [e for _, e in seps],
                                                                         [s for s, _ in seps] + [len(seg)])
                     if seg[a:b].strip()]
        else:
            at = norm.find("\n", colon.end()) + 1
            while 0 < at < len(norm):
                nl = norm.find("\n", at) % (len(norm) + 1)
                m = _MARKER.match(norm, at, nl)
                if not m:
                    break
                items.append((m.end(), nl))
                at = nl + 1
        for lo, hi in items:
            for s, e, pfx in _secrets(norm[lo:hi]):
                before = norm[lo:lo + s].split()
                if _TYPED_IN_APP.search(norm, lo, hi) or _denied_after(norm[lo + e:hi]):
                    break                                   # «- الرمز اللي يوصلك اكتبه بالتطبيق», «والرمز لا تشاركه»
                if not before or (pfx.startswith("و") and all(_item(_bare(x)) for x in before)):
                    return _raw(pos, lo + s, lo + e)
    return None


# A request in English or Arabizi: «Can you send us the verification code?», «send me الكود», «ممكن تعمل send للكود؟»,
